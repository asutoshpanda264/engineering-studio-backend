#!/usr/bin/env node
// One-off generator (plain Node, no build step needed) that turns
// scenarios.export.json — produced by a temporary tsx script run from
// inside the frontend repo, importing its real SCENARIOS array — into a
// committed Flyway migration. See masterdoc/phase-2-scenario-crud/decisions.md
// for why this is a committed SQL migration, not a runtime import step.
//
// Usage: node generate-seed-sql.js <path-to-scenarios.export.json> <output-sql-path>

const fs = require("node:fs");

const [, , inputPath, outputPath] = process.argv;
if (!inputPath || !outputPath) {
  console.error("Usage: node generate-seed-sql.js <input.json> <output.sql>");
  process.exit(1);
}

const scenarios = JSON.parse(fs.readFileSync(inputPath, "utf8"));

// Postgres dollar-quoting ($j$...$j$) instead of manual '-escaping — JSON
// blobs and story text routinely contain apostrophes (contractions,
// possessives), and hand-escaping every single quote is exactly the kind
// of thing that silently breaks on one unusual scenario body. A tag
// distinct from the content itself ($j$) makes this safe as long as no
// scenario's JSON literally contains the substring "$j$", which none do
// (verified: JSON.stringify never emits raw `$`-sequences like that).
function dollarQuote(value) {
  return `$j$${value}$j$`;
}

function jsonbOrNull(value) {
  return value === undefined || value === null ? "NULL" : `${dollarQuote(JSON.stringify(value))}::jsonb`;
}

function textLiteral(value) {
  return dollarQuote(value);
}

function numberOrNull(value) {
  return value === undefined || value === null ? "NULL" : String(value);
}

function boolLiteral(value) {
  return value ? "TRUE" : "FALSE";
}

const lines = [];
lines.push("-- V2.1: seed the 32 existing Workshop scenarios from the frontend");
lines.push("-- (src/scenarios/index.ts), generated by tools/migrate-scenarios/generate-seed-sql.js.");
lines.push("-- ON CONFLICT DO NOTHING makes this safe to re-run / re-apply.");
lines.push("");

for (const s of scenarios) {
  lines.push(
    `INSERT INTO scenarios (id, version, status, title, difficulty, topics, suggested_time_limit_minutes, story, starting_entities, starting_connections, traffic_pattern, duration_ms, seed, constraints, given_node_ids, locked_fields, budget_usd, requires_gated_tool_calls, hints, learning_goals, capacity_estimate, reflection, optimal_solution)`
  );
  lines.push("VALUES (");
  lines.push(`  ${textLiteral(s.id)},`);
  lines.push(`  1,`);
  lines.push(`  'PUBLISHED',`);
  lines.push(`  ${textLiteral(s.title)},`);
  lines.push(`  ${s.difficulty},`);
  lines.push(`  ${jsonbOrNull(s.topics)},`);
  lines.push(`  ${numberOrNull(s.suggestedTimeLimitMinutes)},`);
  lines.push(`  ${textLiteral(s.story)},`);
  lines.push(`  ${jsonbOrNull(s.startingEntities)},`);
  lines.push(`  ${jsonbOrNull(s.startingConnections)},`);
  lines.push(`  ${jsonbOrNull(s.trafficPattern)},`);
  lines.push(`  ${s.durationMs},`);
  lines.push(`  ${s.seed},`);
  lines.push(`  ${jsonbOrNull(s.constraints)},`);
  lines.push(`  ${jsonbOrNull(s.givenNodeIds)},`);
  lines.push(`  ${jsonbOrNull(s.lockedFields)},`);
  lines.push(`  ${numberOrNull(s.budgetUsd)},`);
  lines.push(`  ${boolLiteral(s.requiresGatedToolCalls)},`);
  lines.push(`  ${jsonbOrNull(s.hints)},`);
  lines.push(`  ${jsonbOrNull(s.learningGoals)},`);
  lines.push(`  ${jsonbOrNull(s.capacityEstimate)},`);
  lines.push(`  ${jsonbOrNull(s.reflection)},`);
  lines.push(`  ${jsonbOrNull(s.optimalSolution)}`);
  lines.push(")");
  lines.push("ON CONFLICT (id) DO NOTHING;");
  lines.push("");
}

fs.writeFileSync(outputPath, lines.join("\n"));
console.log(`Wrote ${scenarios.length} INSERT statements to ${outputPath}`);
